export const searchSchema = `
CREATE EXTENSION IF NOT EXISTS unaccent;
CREATE TEXT SEARCH CONFIGURATION curator_search (COPY = pg_catalog.simple);
ALTER TEXT SEARCH CONFIGURATION curator_search ALTER MAPPING FOR
  hword, hword_part, word WITH unaccent, simple;

CREATE VIEW content_search_documents AS
SELECT p.id publication_id,
  COALESCE(r.corrected_analysis_json::jsonb->>'title',a.title,
    NULLIF(trim(p.caption),''),NULLIF(trim(p.author),''),'Sin título') title,
  COALESCE(r.corrected_analysis_json::jsonb->>'tags',a.tags_json,'') tags,
  COALESCE(r.corrected_analysis_json::jsonb->>'summary',a.summary,'') summary,
  concat_ws(' ',p.author,p.caption,p.transcript_text,
    COALESCE(r.corrected_category,a.category),a.subcategory,a.visual_description,
    a.why_interesting,a.next_action,a.entities_json,a.facets_json,
    r.corrected_analysis_json,r.notes) body
FROM publications p
LEFT JOIN analyses a ON a.publication_id=p.id
LEFT JOIN publication_reviews r ON r.publication_id=p.id
WHERE p.processing_status IN ('ready_for_analysis','analyzed');

CREATE TABLE content_search (
  publication_id TEXT PRIMARY KEY REFERENCES publications(id) ON DELETE CASCADE,
  document TSVECTOR NOT NULL
);
CREATE INDEX idx_content_search_document ON content_search USING GIN(document);

CREATE FUNCTION curator_refresh_search(publication TEXT) RETURNS VOID LANGUAGE plpgsql AS $$
BEGIN
  -- Serialize changes to a publication and its analysis/review before reading
  -- the document, so concurrent writers cannot leave a stale search vector.
  PERFORM id FROM publications WHERE id=publication FOR UPDATE;
  DELETE FROM content_search WHERE publication_id=publication;
  INSERT INTO content_search(publication_id,document)
  SELECT publication_id,
    setweight(to_tsvector('curator_search',title),'A') ||
    setweight(to_tsvector('curator_search',tags),'B') ||
    setweight(to_tsvector('curator_search',summary),'C') ||
    setweight(to_tsvector('curator_search',body),'D')
  FROM content_search_documents WHERE publication_id=publication
  ON CONFLICT(publication_id) DO UPDATE SET document=excluded.document;
END $$;

CREATE FUNCTION curator_search_changed() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE publication TEXT;
BEGIN
  IF TG_TABLE_NAME='publications' THEN
    IF TG_OP='DELETE' THEN publication=OLD.id; ELSE publication=NEW.id; END IF;
  ELSE
    IF TG_OP='DELETE' THEN publication=OLD.publication_id; ELSE publication=NEW.publication_id; END IF;
  END IF;
  PERFORM curator_refresh_search(publication);
  RETURN NULL;
END $$;

CREATE TRIGGER content_search_publication AFTER INSERT OR UPDATE OR DELETE ON publications
  FOR EACH ROW EXECUTE FUNCTION curator_search_changed();
CREATE TRIGGER content_search_analysis AFTER INSERT OR UPDATE OR DELETE ON analyses
  FOR EACH ROW EXECUTE FUNCTION curator_search_changed();
CREATE TRIGGER content_search_review AFTER INSERT OR UPDATE OR DELETE ON publication_reviews
  FOR EACH ROW EXECUTE FUNCTION curator_search_changed();
INSERT INTO content_search(publication_id,document)
SELECT publication_id,
  setweight(to_tsvector('curator_search',title),'A') ||
  setweight(to_tsvector('curator_search',tags),'B') ||
  setweight(to_tsvector('curator_search',summary),'C') ||
  setweight(to_tsvector('curator_search',body),'D')
FROM content_search_documents;
`;
